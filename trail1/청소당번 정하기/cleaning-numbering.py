'''
0일을 기점으로 2일마다 교실 청소를, 3일마다 복도 청소를, 12일마다 화장실 청소를 합니다.
날짜가 겹치는 날에는 주기가 더 긴 것을 하기로 했습니다.
n일간 진행했을 때 각 장소의 청소 횟수를 차례로 출력하는 프로그램을 작성해주세요. 단, 시작 날인 0일에는 청소를 진행하지 않습니다.
'''

n = int(input())

room = 0  # 교실
hall = 0  # 복도
rest = 0  # 화장실

for i in range(1, n+1):
    if i % 2 == 0:              # 2의 배수일 때
        if i % 12 == 0:         # 12의 배수
            rest += 1
        elif i % 3 == 0:        # 3의 배수인 경우
            hall += 1
        else:                   # 2의 배수이기만 할 때
            room += 1
    else:                       # 2의 배수가 아닐 때
        if i % 3 == 0:          # 3의 배수인 경우
            hall += 1


print(room, hall, rest)
