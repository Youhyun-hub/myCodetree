'''
2011년 11월 11일 11시 11분에서 시작하여 2011년 11월 A일 B시 C분까지 몇 분이 걸리는지를 계산하는 프로그램을 작성해보세요.
'''


a, b, c = map(int, input().split()) # a - 날짜, b - 시, c - 분

# 24시간(하루) = 1,440분

if a <= 11 and b < 11:
    diff = -1  # 11월 11일 11시 11분보다 앞설 경우
    
elif a >= 11:  # 11일 이후
    if c - 11 < 0:
        diff = 60 + c - 11 + ((b - 11 - 1) * 60) + ((a - 11) * 1440)
    else:
        diff = c - 11 + ((b - 11) * 60) + ((a - 11) * 1440)

print(diff)

